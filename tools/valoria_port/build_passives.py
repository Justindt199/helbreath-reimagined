#!/usr/bin/env python3
"""Ports VALORIA's passive skill tree into Helbreath Reimagined.

Run from the repo root:  python3 tools/valoria_port/build_passives.py

Reads   tools/valoria_port/valoria_data/passives.json   (VALORIA's 301 nodes)
        tools/valoria_port/item_map.json                (Helbreath names of the two passive relics)
Writes  Source/Shared/ValoriaPassiveTree.h              (the tree, compiled into the client and both servers)
        Server/configs/droplist.xml                     (the relics, in the bosses' rarest drop tier)

The conversion rules (the same for every node):
  * Each node's values become whole numbers: halves round away from zero (0.5 -> 1, 1.5 -> 2, 2.5 -> 3,
    -7.5 -> -8), and nothing smaller than 1 survives as 0 (0.25 regen -> 1).
  * Positions, links, names and kinds (root / small / notable / keystone) are VALORIA's.
  * Node 0 is the root (The Wanderer's Heart): always taken, costs nothing.
  * Relics (Orb of Unmaking, Tome of the Unbound Path) drop only from bosses: each joins the boss's
    rarest drop tier with the same weight as the rarest item already in that tier.
"""
import json, math, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
HERE = os.path.dirname(__file__)
OUT_H = os.path.join(ROOT, 'Source', 'Shared', 'ValoriaPassiveTree.h')
DROPLIST = os.path.join(ROOT, 'Server', 'configs', 'droplist.xml')

# Order matters: it is the PMod enum in ValoriaPassives.h and the client's display order.
MODS = ['str', 'dex', 'vit', 'int', 'mag', 'hp', 'mp', 'def', 'dmg_pct', 'hp_pct', 'mp_pct', 'def_pct', 'xp',
        'crit', 'crit_dmg', 'spell_dmg', 'atk_spd', 'dodge', 'speed', 'regen', 'mp_regen', 'dmg_red', 'sp_pct',
        'item_find', 'gold_find', 'boss_dmg', 'lifesteal', 'mp_steal', 'thorns']
KINDS = ['root', 'small', 'notable', 'keystone']
BRANCHES = ['', 'might', 'finesse', 'arcana']
BOSSES = ['Abaddon', 'Hellclaw', 'Tigerworm', 'Wyvern', 'Fire-Wyvern']
RELIC_MARK = '<!-- VALORIA passive relic -->'


def whole(x):
    r = int(math.floor(abs(x) + 0.5))
    return int(math.copysign(max(1, r), x)) if x else 0


def c_str(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def build_header(nodes):
    keys = list(nodes)
    assert keys[0] == 'origin' and nodes['origin']['kind'] == 'root'
    index = {k: i for i, k in enumerate(keys)}
    for k, v in nodes.items():                       # links must be two-way
        for l in v['links']:
            assert k in nodes[l]['links'], (k, l)
    unknown = {m for v in nodes.values() for m in v['mods']} - set(MODS)
    if unknown: sys.exit('unknown passive modifiers: %s' % sorted(unknown))
    max_links = max(len(v['links']) for v in nodes.values())
    max_mods = max(len(v['mods']) for v in nodes.values())

    out = ['// VALORIA passive tree: generated by tools/valoria_port/build_passives.py, do not edit by hand.',
           '// %d nodes. Rules: see the script.' % len(keys),
           '#pragma once', '', 'namespace ValoriaPassive {', '',
           'enum PMod {']
    out += ['\tPM_%s,' % m.upper() for m in MODS] + ['\tPM_COUNT', '};', '']
    out += ['enum PKind { %s };' % ', '.join('PK_%s' % k.upper() for k in KINDS), '']
    out += ['const int NODE_COUNT = %d;' % len(keys), 'const int NODE_LINKS = %d;' % max_links,
            'const int NODE_MODS  = %d;' % max_mods, '',
            'struct Node {',
            '\tconst char * name;',
            '\tunsigned char kind, branch;\t// PKind; 0 none, 1 Might, 2 Finesse, 3 Arcana',
            '\tshort x, y;\t\t\t\t\t// VALORIA tree position (root at 0,0, y down)',
            '\tunsigned char links;',
            '\tshort link[NODE_LINKS];',
            '\tunsigned char mods;',
            '\tunsigned char mod[NODE_MODS];\t// PMod',
            '\tsigned char val[NODE_MODS];',
            '};', '',
            'static const Node NODES[NODE_COUNT] = {']
    for k in keys:
        v = nodes[k]
        links = [index[l] for l in v['links']]
        mods = list(v['mods'].items())
        vals = [whole(x) for _, x in mods]
        assert all(-128 <= x <= 127 for x in vals)
        pad = lambda a, n: a + [0] * (n - len(a))
        out.append('\t{ %s, %d, %d, %d, %d, %d, { %s }, %d, { %s }, { %s } },\t// %s' % (
            c_str(v['name']), KINDS.index(v['kind']), BRANCHES.index(v['branch']), int(v['pos'][0]), int(v['pos'][1]),
            len(links), ', '.join(map(str, pad(links, max_links))),
            len(mods), ', '.join(map(str, pad([MODS.index(m) for m, _ in mods], max_mods))),
            ', '.join(map(str, pad(vals, max_mods))), k))
    out += ['};', '', '}\t// namespace ValoriaPassive', '']
    open(OUT_H, 'w', newline='\r\n').write('\n'.join(out))
    return len(keys)


def add_drops(relics):
    text = open(DROPLIST, encoding='latin-1', newline='').read()
    nl = '\r\n' if '\r\n' in text else '\n'
    text = ''.join(l for l in text.splitlines(True) if RELIC_MARK not in l)    # rerunnable
    added = []
    for boss in BOSSES:
        m = re.search(r'<npc_t name="%s"[^>]*>(.*?)</npc_t>' % re.escape(boss), text, re.S)
        if not m: sys.exit('boss not in droplist.xml: ' + boss)
        body = m.group(1)
        tiers = list(re.finditer(r'<tier_t type="secondary" prob="(\d+)">(.*?)</tier_t>', body, re.S))
        rarest = min(tiers, key=lambda t: int(t.group(1)))     # least likely tier
        probs = [int(p) for n, p in re.findall(r'<item_t name="([^"]+)" prob="(\d+)"/>', rarest.group(2)) if n != 'nothing']
        w = min(probs)
        close = m.start(1) + rarest.end(2)                       # just before </tier_t>
        indent = '\t\t\t'
        ins = ''.join('%s<item_t name="%s" prob="%d"/>%s%s' % (indent, r, w, RELIC_MARK, nl) for r in relics)
        line_start = text.rfind('\n', 0, close) + 1               # put the lines before the closing tag's line
        text = text[:line_start] + ins + text[line_start:]
        added.append('%s (weight %d in its prob-%s tier)' % (boss, w, rarest.group(1)))
    open(DROPLIST, 'w', encoding='latin-1', newline='').write(text)
    return added


def main():
    nodes = json.load(open(os.path.join(HERE, 'valoria_data', 'passives.json')))['nodes']
    item_map = json.load(open(os.path.join(HERE, 'item_map.json')))
    relics = [item_map['refund_orb'][0], item_map['passive_tome'][0], item_map['blessed_stone'][0]]
    n = build_header(nodes)
    print('wrote', OUT_H, n, 'nodes')
    for a in add_drops(relics):
        print('drops:', a)


if __name__ == '__main__':
    main()
