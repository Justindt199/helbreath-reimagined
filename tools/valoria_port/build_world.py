#!/usr/bin/env python3
"""Places VALORIA's shrines and treasure chests on Helbreath's maps.

Run from the repo root:  python3 tools/valoria_port/build_world.py

Reads   Server/HG Server/MAPDATA/*.amd        (which tiles can be walked on)
        Server/configs/valoria_recipes.txt    (VALORIA gear and the level it needs)
Writes  Source/Shared/ValoriaWorld.h          (compiled into the client and the game server)

The rules (the same for every map):
  * MAPS below says how many shrines and chests a map gets and the chests' tier (1-5, as VALORIA's).
  * A spot is open ground: every tile within 3 of it can be walked on, none is a teleport, it is
    in the map's main walkable area and at least 16 tiles from the map's edge.
  * Spots are spread out: each new one is the open spot farthest from the ones already placed
    (the first is the one nearest the middle of the map). Shrines are placed first.
  * Shrines take VALORIA's five blessings in turn, carrying on from map to map.
To move one by hand, edit FIXED below (map, x, y replace the spot the rules chose) and run again.
"""
import os, re, sys
from collections import deque

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
MAPDIR = os.path.join(ROOT, 'Server', 'HG Server', 'MAPDATA')
OUT = os.path.join(ROOT, 'Source', 'Shared', 'ValoriaWorld.h')

# map: (shrines, chests, chest tier)
MAPS = [
    ('arefarm', 1, 2, 1), ('elvfarm', 1, 2, 1), ('aresden', 2, 1, 1), ('elvine', 2, 1, 1),
    ('middleland', 5, 6, 2), ('huntzone1', 1, 2, 2), ('huntzone2', 1, 2, 2),
    ('aresdend1', 1, 2, 2), ('elvined1', 1, 2, 2), ('middled1n', 1, 3, 3),
    ('2ndmiddle', 3, 4, 3), ('dglv2', 1, 3, 3), ('dglv3', 1, 3, 3), ('toh1', 1, 2, 3),
    ('dglv4', 1, 3, 4), ('toh2', 1, 2, 4), ('toh3', 1, 2, 4), ('icebound', 2, 3, 4),
    ('druncncity', 1, 3, 4), ('maze', 1, 2, 4),
    ('procella', 2, 3, 5), ('inferniaa', 1, 3, 5), ('inferniab', 1, 3, 5), ('abaddon', 0, 2, 5),
]
FIXED = {}		# (map, index of the spot in that map, shrines first): (x, y)
CLEAR, EDGE = 3, 16

def load(name):
    for f in os.listdir(MAPDIR):
        if f.lower() == name + '.amd':
            d = open(os.path.join(MAPDIR, f), 'rb').read()
            head = d[:256].decode('latin-1')
            w = int(re.search(r'MAPSIZEX\s*=\s*(\d+)', head).group(1))
            h = int(re.search(r'MAPSIZEY\s*=\s*(\d+)', head).group(1))
            ts = int(re.search(r'TILESIZE\s*=\s*(\d+)', head).group(1))
            walk = [[False] * w for _ in range(h)]
            tele = [[False] * w for _ in range(h)]
            for y in range(h):
                row = 256 + y * w * ts
                for x in range(w):
                    b = d[row + x * ts + 8]
                    walk[y][x] = not (b & 0x80)
                    tele[y][x] = bool(b & 0x40)
            return w, h, walk, tele
    sys.exit('no map file for ' + name)

def spots(name, n):
    w, h, walk, tele = load(name)
    # the main walkable area
    comp = [[-1] * w for _ in range(h)]
    best, bestn, c = -1, 0, 0
    for sy in range(h):
        for sx in range(w):
            if not walk[sy][sx] or comp[sy][sx] >= 0: continue
            q = deque([(sx, sy)]); comp[sy][sx] = c; k = 0
            while q:
                x, y = q.popleft(); k += 1
                for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                    X, Y = x + dx, y + dy
                    if 0 <= X < w and 0 <= Y < h and walk[Y][X] and comp[Y][X] < 0:
                        comp[Y][X] = c; q.append((X, Y))
            if k > bestn: best, bestn = c, k
            c += 1
    edge = min(EDGE, w // 6, h // 6)
    cand = []
    for y in range(edge, h - edge):
        for x in range(edge, w - edge):
            if comp[y][x] != best: continue
            if all(walk[y + j][x + i] and not tele[y + j][x + i]
                   for j in range(-CLEAR, CLEAR + 1) for i in range(-CLEAR, CLEAR + 1)):
                cand.append((x, y))
    if len(cand) < n: sys.exit('%s: only %d open spots' % (name, len(cand)))
    cx, cy = w / 2, h / 2
    out = [min(cand, key=lambda p: ((p[0] - cx) ** 2 + (p[1] - cy) ** 2, p))]
    dist = [(p[0] - out[0][0]) ** 2 + (p[1] - out[0][1]) ** 2 for p in cand]
    while len(out) < n:
        i = max(range(len(cand)), key=lambda k: (dist[k], -cand[k][1], -cand[k][0]))
        out.append(cand[i])
        for k, p in enumerate(cand):
            d2 = (p[0] - cand[i][0]) ** 2 + (p[1] - cand[i][1]) ** 2
            if d2 < dist[k]: dist[k] = d2
    return out

def main():
    L = ['// ValoriaWorld.h: VALORIA\'s shrines and treasure chests on Helbreath\'s maps.',
         '// Generated by tools/valoria_port/build_world.py (the placement rules are there): do not edit.',
         '// The game server runs them in HG Server\\WorldProps.cpp; the client draws them in UI\\WorldProps.cpp.',
         '#pragma once', '', 'namespace World {', '',
         'enum Kind { SHRINE_MIGHT, SHRINE_SWIFTNESS, SHRINE_WISDOM, SHRINE_FORTUNE, SHRINE_VIGOR, CHEST };',
         'const int SHRINE_KINDS = 5;',
         'const int SHRINE_RECHARGE = 300;	// seconds, as VALORIA (the blessing itself lasts 240: Shared\\ValoriaUse.h)',
         'const int CHEST_REFILL   = 900;',
         'const int TOUCH_RANGE    = 2;		// tiles',
         '',
         'struct Prop { const char * map; short x, y; unsigned char kind, tier; };',
         'static const Prop kProps[] = {']
    kind, total = 0, [0, 0]
    for name, ns, nc, tier in MAPS:
        sp = spots(name, ns + nc)
        for i, (x, y) in enumerate(sp):
            x, y = FIXED.get((name, i), (x, y))
            if i < ns:
                L.append('\t{ "%s", %d, %d, %d, 0 },' % (name, x, y, kind)); kind = (kind + 1) % 5; total[0] += 1
            else:
                L.append('\t{ "%s", %d, %d, CHEST, %d },' % (name, x, y, tier)); total[1] += 1
    L += ['};', 'const int PROP_COUNT = (int)(sizeof(kProps) / sizeof(kProps[0]));', '']
    # VALORIA gear a chest can hold: the craftable gear, by the level it needs
    L += ['// What a chest can hold besides gold (VALORIA chest.gd): a healing potion and a crafting material of',
          '// its tier, and with a chance of 35% + 8% per tier one piece of VALORIA gear of its tier (kGear:',
          '// the craftable items and the level they need; the server keeps the ones that are worn or wielded).',
          'static const unsigned short kChestGold[5] = { 20, 60, 140, 320, 700 };	// x1 to x3',
          'static const char * const kChestPotion[5] = { "SmallHealthPotion", "HealthPotion", "GreaterHealthPotion", "GreaterHealthPotion", "SuperiorHealthPotion" };',
          'static const char * const kChestMaterial[5] = { "ForgeDust", "VerdantEssence", "AzureEssence", "VioletEssence", "RadiantEssence" };',
          'inline int ChestGearPct(int tier) { return 35 + 8 * tier; }',
          'struct Gear { const char * name; unsigned char level; };',
          'static const Gear kGear[] = {']
    for ln in open(os.path.join(ROOT, 'Server', 'configs', 'valoria_recipes.txt'), encoding='latin-1'):
        if ln.startswith('//') or not ln.strip(): continue
        p = ln.split('\t')
        L.append('\t{ "%s", %d },' % (p[0].strip(), min(255, int(p[1]))))
    L += ['};', 'const int GEAR_COUNT = (int)(sizeof(kGear) / sizeof(kGear[0]));', '',
          'inline bool SameMap(const char * a, const char * b)',
          '{', '\tfor (; *a && *b; a++, b++) if ((*a | 0x20) != (*b | 0x20)) return false;', '\treturn *a == 0 && *b == 0;', '}',
          '', '} // namespace World', '']
    open(OUT, 'w', encoding='latin-1', newline='\r\n').write('\n'.join(L))
    print('%d shrines, %d chests on %d maps' % (total[0], total[1], len(MAPS)))

if __name__ == '__main__':
    main()
