#!/usr/bin/env python3
"""Ports VALORIA's items into Helbreath Reimagined.

Run from the repo root:  python3 tools/valoria_port/build_items.py

Reads   tools/valoria_port/valoria_data/items.json   (VALORIA's item list)
        Server/Login Server/Config/Item*.cfg         (Helbreath items, used as templates)
Writes  Server/Login Server/Config/ItemValoria<N>.cfg (the item rows, split so each file stays under
                                                      16000 bytes: a file near 20 KB arrived damaged at the game server)
        Client/CONTENTS/ItemName.cfg                 (block between the VALORIA markers)
        Server/configs/valoria_gear.txt              (stat bonuses of VALORIA gear, read by the game server)
        Client/CONTENTS/valoria_gear.txt             (same table, read by the client)
        tools/valoria_port/item_map.json             (VALORIA id -> Helbreath item name(s), for recipes)
        tools/valoria_port/sprite_frames.json        (frame order of valoria_items.pak, for build_sprites.py)

The conversion rules (the same for every item; see RULES.md):
  * Required level  = VALORIA required level x 140 / 80, rounded (VALORIA's highest is 79 -> 138).
  * VALORIA gloves are not ported: Helbreath has no glove slot.
  * Weapon damage   = HB average 3.5 x (VALORIA average / 6.5) ^ 0.69, split over the template's dice
                      (more dice for big hitters, so no die has more than about 14 sides).
  * Armour defence  = the slot's best Helbreath value x (VALORIA defence / slot's best VALORIA defence).
  * Price           = VALORIA price / 4. Items VALORIA doesn't sell in a shop can't be sold to a shop here either.
  * Stat bonuses (STR, DEX, VIT, INT, MAG, HP, MP, crit, and DEF on jewellery) go to valoria_gear.txt.
  * The worn look, weight, swing speed, weapon skill and class come from a Helbreath template item.
  * Armour worn on the body (helmets, body armour, arm pieces, leggings) is made in a male (M) and a
    female (W) version, as Helbreath draws men and women with different sprites.
"""
import json, math, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DATA = os.path.join(os.path.dirname(__file__), 'valoria_data')
CFG_DIR = os.path.join(ROOT, 'Server', 'Login Server', 'Config')
ITEM_CFG = os.path.join(CFG_DIR, 'Item3.cfg')
NAME_CFG = os.path.join(ROOT, 'Client', 'CONTENTS', 'ItemName.cfg')
BEGIN = '// ==== VALORIA items: generated by tools/valoria_port/build_items.py, do not edit by hand ===='
END = '// ==== end of VALORIA items ===='

FIRST_ID, LAST_ID = 1103, 1499          # free item numbers below MAXITEMTYPES (1500)
SPRITE = 23                             # valoria_items.pak is registered as item sprite 23
MAX_VAL_LEVEL, MAX_HB_LEVEL = 80, 140

# Helbreath columns after "Item =" (see CGame::_bDecodeItemConfigFileContents)
COLS = ['id', 'name', 'type', 'epos', 'eff', 'v1', 'v2', 'v3', 'v4', 'v5', 'v6', 'dur', 'seff', 'spr', 'sfrm',
        'price', 'wt', 'appr', 'spd', 'lvl', 'sex', 'sa1', 'sa2', 'skill', 'catg', 'color', 'log']

# Existing Helbreath items that VALORIA's are the same thing as: reused, not duplicated.
REUSE = {'iron_ore': 'IronOre', 'ruby': 'Ruby', 'sapphire': 'Sapphire', 'emerald': 'Emerald', 'diamond': 'Diamond'}

# Not ported in this stage (they need the enchanting / empowering / passive-tree / buff stages, or
# VALORIA's quests, which Helbreath doesn't have).
LATER_TYPES = {'enhance', 'elixir', 'quest', 'relic'}
LATER_IDS = {'crypt_scroll', 'xp_scroll', 'smith_luck_scroll'}
# Relics the passive tree uses (Source/Shared/ValoriaPassives.h): ported now, the other relics later.
PASSIVE_RELICS = {'passive_tome', 'refund_orb'}
# Usable items (Source/Shared/ValoriaUse.h): buff number / Valoria modifier + 1 (100 = Blessed Upgrade Stone).
USE_BUFFS = [('elixir_strength', 0), ('elixir_ironskin', 1), ('elixir_swiftness', 2), ('elixir_wisdom', 3), ('xp_scroll', 4)]
USE_INFUSE = [('rune_might', 1), ('rune_agility', 2), ('rune_vigor', 3), ('rune_intellect', 4), ('rune_sorcery', 5),
              ('rune_warding', 8), ('blessed_stone', 100)]
# Added once crit and gold / item find worked in Helbreath: after the others, so item numbers stay put.
USE_LATER = [('elixir_fortune', 'RedPotion', dict(type=3, eff=36, v1=5)), ('rune_precision', 'Dye(Indigo)', dict(eff=35, v1=9, dur=1))]
DROPPED_TYPES = {'gloves'}               # Helbreath has no glove slot

# Template for each weapon (worn look, swing speed, skill, dice count). Order matters: first match wins.
WEAPON_TEMPLATES = [
    (r'dagger', 'Dagger'),
    (r'short_sword', 'ShortSword'),
    (r'staff|scepter', 'MagicWand(MS10)'),
    (r'hand_axe', 'LightAxe'),
    (r'battle_axe|war_axe', 'BattleAxe'),
    (r'executioners_axe|abyssal_cleaver', 'BattleAxe'),
    (r'club|mace|morning_star', 'DoubleAxe'),            # Helbreath has no one-handed mace; a one-handed axe swing
    (r'war_hammer', 'Hammer'),
    (r'titan_maul', 'BarbarianHammer'),
    (r'broadsword', 'BroadSword'),
    (r'great_sword', 'GreatSword'),
    (r'dragonslayer|hellbrand|nightfall', 'GiantSword'),
    (r'.', 'LongSword'),                                  # long_sword, knight_blade, initiate_blade, wyrmfang, aetherion
]
# (M, W) templates for armour, by VALORIA type, by id pattern.
ARMOR_TEMPLATES = {
    'helmet': [(r'wizard|crown', 'Wizard-Cap'), (r'leather', 'Helm'), (r'iron', 'Helm'), (r'horned', 'Horned-Helm'),
               (r'dragon|deathknight', 'KnightFullHelm'), (r'.', 'FullHelm')],
    'armor': [(r'robe|shroud', 'Robe'), (r'cloth|tunic', 'LeatherArmor'), (r'leather|studded', 'LeatherArmor'),
              (r'chain', 'ChainMail'), (r'scale', 'ScaleMail'), (r'knight|dragon|abyssal|ridgebreaker|cinder', 'KnightPlateMail'),
              (r'.', 'PlateMail')],
    'hauberk': [(r'wyrm', 'KnightHauberk'), (r'.', 'Hauberk')],
    'gloves': [(r'silk|wraps', 'WizardHauberk'), (r'leather', 'Shirt'), (r'.', 'Hauberk')],   # no glove slot in Helbreath: arm slot
    'legs': [(r'skirt|robe|walker', 'Trousers'), (r'cloth|leather|studded', 'Trousers'), (r'chain', 'ChainHose'),
             (r'.', 'PlateLeggings')],
}
SINGLE_TEMPLATES = {
    'boots': [(r'leather', 'Shoes'), (r'.', 'LongBoots')],
    'shield': [(r'wooden', 'WoodShield'), (r'buckler', 'TargeShield'), (r'kite', 'KnightShield'), (r'.', 'TowerShield')],
    'ring': [(r'.', 'RingofWizard')],
    'amulet': [(r'.', 'NecklaceOfMedusa')],
    'material': [(r'.', 'IronOre')],
    'gem': [(r'.', 'Ruby')],
    'loot': [(r'.', 'Ruby')],
    'food': [(r'.', 'Meat')],
    'scroll': [(r'.', 'RecallScroll')],
}
POTION_TEMPLATES = {'heal': 'RedPotion', 'mana': 'BluePotion', 'stamina': 'GreenPotion'}

# Best Helbreath defence (v1) per equip slot, and the slot's best VALORIA defence (worked out below).
HB_SLOT_MAX = {'helmet': 25, 'armor': 75, 'hauberk': 25, 'gloves': 25, 'legs': 25, 'boots': 10, 'shield': 35}
BONUS_KEYS = ['str', 'dex', 'vit', 'int', 'mag', 'hp', 'mp', 'def', 'crit']


def load_hb_items():
    rows = {}
    for f in ['Item.cfg', 'Item2.cfg', 'Item3.cfg']:
        inside = False
        for line in open(os.path.join(CFG_DIR, f), encoding='latin-1'):
            if line.startswith(BEGIN): inside = True
            if line.startswith(END): inside = False; continue
            if inside: continue
            if re.match(r'\s*Item\s*=', line, re.I):
                c = line.split('=', 1)[1].split()
                rows[c[1]] = dict(zip(COLS, c))
    return rows


def pick(table, key):
    for pat, name in table:
        if re.search(pat, key): return name
    raise KeyError(key)


def hb_level(v):
    return min(MAX_HB_LEVEL, int(round(v.get('req_level', 0) * MAX_HB_LEVEL / MAX_VAL_LEVEL)))


def hb_avg_damage(dmg):
    avg = (dmg[0] + dmg[1]) / 2.0
    return 3.5 * (avg / 6.5) ** 0.69


def hb_price(v):
    p = max(1, int(round(v['price'] / 4)))
    sold_in_shop = 'shop' in v
    return p if sold_in_shop else -p


def internal_name(v, key, suffix=''):
    """Helbreath item names have no spaces and at most 20 characters."""
    base = re.sub(r"[^A-Za-z0-9]", '', v['name'].replace("'", '').title())
    room = 20 - len(suffix)
    if len(base) > room:
        words = re.findall(r'[A-Z][a-z0-9]*|[0-9]+', base)
        words = [w for w in words if w not in ('Of', 'The', 'And')] or words
        while len(''.join(words)) > room:                # trim the longest word, one letter at a time
            i = max(range(len(words)), key=lambda j: len(words[j]))
            if len(words[i]) <= 3: break
            words[i] = words[i][:-1]
        base = ''.join(words)[:room]
    return base + suffix


def main():
    items = json.load(open(os.path.join(DATA, 'items.json')))
    hb = load_hb_items()
    hb_lower = {k.lower(): k for k in hb}

    # slot maxima on the VALORIA side
    val_slot_max = {}
    for v in items.values():
        if v['type'] in HB_SLOT_MAX and v.get('def'):
            val_slot_max[v['type']] = max(val_slot_max.get(v['type'], 0), v['def'])

    out_rows, names, gear, item_map, frames, skipped, reused = [], [], [], {}, [], [], []
    used = set()
    next_id = FIRST_ID

    def new_row(tmpl_name, name, display, v, frame, **over):
        nonlocal next_id
        if next_id > LAST_ID: sys.exit('out of free item numbers')
        if name.lower() in hb_lower or name in used: sys.exit('name clash: ' + name)
        used.add(name)
        r = dict(hb[tmpl_name])
        r.update(id=str(next_id), name=name, spr=str(SPRITE), sfrm=str(frame), price=str(hb_price(v)),
                 lvl=str(hb_level(v)), color='0', log='TRUE')
        r.update({k: str(val) for k, val in over.items()})
        next_id += 1
        out_rows.append(r)
        names.append((name, display[:33]))
        bonus = {k: v.get(k, 0) for k in BONUS_KEYS if k != 'def'}
        if v['type'] in ('ring', 'amulet') and v.get('def'): bonus['def'] = v['def']
        if any(bonus.values()):
            gear.append((name, [int(bonus.get(k, 0)) for k in BONUS_KEYS]))
        return name

    for key, v in items.items():
        t = v['type']
        if key in PASSIVE_RELICS:     # added after the Enchanter's Tome, so older item numbers stay put
            continue
        if t in LATER_TYPES or key in LATER_IDS:
            skipped.append((key, 'later stage' if t != 'quest' else 'VALORIA quest item'))
            continue
        if t in DROPPED_TYPES:
            skipped.append((key, 'no glove slot in Helbreath'))
            continue
        if key in REUSE:
            item_map[key] = [REUSE[key]]
            continue
        # Same name as an existing Helbreath item: it is that item, reuse it.
        plain = internal_name(v, key)
        if plain.lower() in hb_lower and t not in ARMOR_TEMPLATES:
            item_map[key] = [hb_lower[plain.lower()]]
            reused.append((key, hb_lower[plain.lower()]))
            continue
        if t in ARMOR_TEMPLATES and all(internal_name(v, key, '(%s)' % s).lower() in hb_lower for s in 'MW'):
            item_map[key] = [hb_lower[internal_name(v, key, '(%s)' % s).lower()] for s in 'MW']
            reused.append((key, item_map[key][0]))
            continue
        frame = len(frames)
        frames.append({'key': key, 'icon': v['icon']})
        display = v['name']

        if t == 'weapon':
            tmpl = hb[pick(WEAPON_TEMPLATES, key)]
            avg = hb_avg_damage(v['dmg'])
            n = max(int(tmpl['v1']), int(math.ceil(avg / 7.0)))     # no die bigger than about 14 sides
            sides = max(2, int(round(2 * avg / n - 1)))
            lsides = sides + 1
            over = dict(v1=n, v2=sides, v3=0, v4=n, v5=lsides, v6=0)
            if tmpl['eff'] == '13':                              # wand/staff: v4 is mana save, keep it 0
                over.update(v4=0, v5=0, v6=0)
            item_map[key] = [new_row(tmpl['name'], internal_name(v, key), display, v, frame, **over)]

        elif t in ARMOR_TEMPLATES:
            base = pick(ARMOR_TEMPLATES[t], key)
            made = []
            for sex in ('M', 'W'):
                tn = '%s(%s)' % (base, sex)
                if tn not in hb:                                   # e.g. Shirt(M) only exists as one sex
                    tn = '%s(%s)' % ('Hauberk', sex)
                tmpl = hb[tn]
                over = {}
                if v.get('def'):
                    v1 = max(1, int(round(HB_SLOT_MAX[t] * v['def'] / val_slot_max[t])))
                    tv1, tv2 = int(tmpl['v1']), int(tmpl['v2'])
                    v2 = max(1, int(round(v1 * tv2 / tv1))) if tv1 > 0 else tv2
                    over = dict(v1=v1, v2=v2)
                made.append(new_row(tn, internal_name(v, key, '(%s)' % sex), display, v, frame, **over))
            item_map[key] = made

        elif t in ('boots', 'shield'):
            tmpl = hb[pick(SINGLE_TEMPLATES[t], key)]
            over = {}
            if v.get('def'):
                v1 = max(1, int(round(HB_SLOT_MAX[t] * v['def'] / val_slot_max[t])))
                tv1, tv2 = int(tmpl['v1']), int(tmpl['v2'])
                over = dict(v1=v1, v2=max(1, int(round(v1 * tv2 / tv1))) if tv1 > 0 else tv2)
            item_map[key] = [new_row(tmpl['name'], internal_name(v, key), display, v, frame, **over)]

        elif t in ('ring', 'amulet'):
            tmpl = hb[pick(SINGLE_TEMPLATES[t], key)]
            # Helbreath's own jewellery effect is switched off: the bonuses come from valoria_gear.txt.
            item_map[key] = [new_row(tmpl['name'], internal_name(v, key), display, v, frame,
                                     eff=0, v1=0, v2=0, v3=0, v4=0, v5=0, v6=0, sa1=0, sa2=0)]

        elif t == 'potion':
            kind = next(k for k in ('heal', 'mana', 'stamina') if k in v)
            tmpl = hb[POTION_TEMPLATES[kind]]
            # Restores (VALORIA amount / 2) on average: 3 dice of a fixed size plus the rest as a bonus.
            avg = v[kind] / 2.0
            sides = 8
            bonus = max(0, int(round(avg - 3 * (sides + 1) / 2.0)))
            item_map[key] = [new_row(tmpl['name'], internal_name(v, key), display, v, frame,
                                     v1=3, v2=sides, v3=bonus)]

        elif t == 'food':
            tmpl = hb['Meat']
            avg = v.get('regen_hp', 40) / 4.0
            item_map[key] = [new_row('Meat', internal_name(v, key), display, v, frame,
                                     v1=2, v2=8, v3=max(0, int(round(avg - 9))))]

        elif t == 'scroll':
            item_map[key] = [new_row('RecallScroll', internal_name(v, key), display, v, frame)]

        elif t in ('material', 'gem', 'loot'):
            item_map[key] = [new_row(pick(SINGLE_TEMPLATES[t], key), internal_name(v, key), display, v, frame)]
        else:
            skipped.append((key, 'no Helbreath equivalent for type ' + t))

    # ---- Helbreath Reimagined's own items (not in VALORIA's item list)
    # The Enchanter's Tome: the tool item that opens the enchanting window, like the Alchemy Bowl opens
    # alchemy. Sold by the Shopkeeper (Client/CONTENTS/Shop/contents2.txt) for VALORIA's lesson price.
    frame = len(frames)
    frames.append({'key': 'enchanters_tome', 'icon': 'obj_x_tome'})
    new_row('AlchemyBowl', 'EnchantersTome', "Enchanter's Tome", {'type': 'tool', 'price': 4000, 'shop': 'magic'}, frame)

    # The passive tree's relics (boss drops; used from the passive tree window, see build_passives.py).
    for key in sorted(PASSIVE_RELICS):
        v = items[key]
        frame = len(frames)
        frames.append({'key': key, 'icon': v['icon']})
        item_map[key] = [new_row('Ruby', internal_name(v, key), v['name'], v, frame)]

    # VALORIA's usable items (Source/Shared/ValoriaUse.h): elixirs and the Scroll of Insight give a timed
    # buff (effect 36, value 1 = buff); runes and the Blessed Upgrade Stone are used on gear like a dye
    # (effect 35, value 1 = modifier + 1, or 100 for the stone). Added last, so older item numbers stay put.
    for key, buff in USE_BUFFS:
        v = items[key]
        frame = len(frames)
        frames.append({'key': key, 'icon': v['icon']})
        item_map[key] = [new_row('RedPotion', internal_name(v, key), v['name'], v, frame,
                                 type=3, eff=36, v1=buff, v2=0, v3=0, v4=0, v5=0, v6=0)]
    for key, mod in USE_INFUSE:
        v = items[key]
        frame = len(frames)
        frames.append({'key': key, 'icon': v['icon']})
        item_map[key] = [new_row('Dye(Indigo)', internal_name(v, key), v['name'], v, frame,
                                 eff=35, v1=mod, v2=0, dur=1)]
    for key, tmpl, extra in USE_LATER:
        v = items[key]
        frame = len(frames)
        frames.append({'key': key, 'icon': v['icon']})
        item_map[key] = [new_row(tmpl, internal_name(v, key), v['name'], v, frame, v2=0, v3=0, v4=0, v5=0, v6=0, **extra)]

    # ---- item rows: ItemValoria1.cfg, ItemValoria2.cfg, ... (the login server sends each one separately)
    replace_block(ITEM_CFG, [])                                   # older versions wrote them into Item3.cfg
    header = '// VALORIA items: generated by tools/valoria_port/build_items.py, do not edit by hand.\n'
    files, cur = [], header
    for r in out_rows:
        line = 'Item\t=\t' + '\t'.join(r[c] for c in COLS) + '\n'
        if len(cur) + len(line) > 16000:
            files.append(cur); cur = header
        cur += line
    files.append(cur)
    if len(files) > 4: sys.exit('more than 4 ItemValoria files: raise MAX_EXTRA_ITEMCFG in the login server')
    for i in range(1, 5):
        path = os.path.join(CFG_DIR, 'ItemValoria%d.cfg' % i)
        if i <= len(files): open(path, 'w', newline='\r\n').write(files[i - 1])
        elif os.path.exists(path): open(path, 'w', newline='\r\n').write(header)

    # ---- client display names
    nl = [BEGIN + '\n'] + ['Item=%s=%s=\n' % (n, d.replace('=', '-')) for n, d in names] + [END + '\n']
    replace_block(NAME_CFG, nl)

    # ---- gear bonus table (server and client read the same file)
    head = ['// Stat bonuses of VALORIA gear while equipped. Generated by tools/valoria_port/build_items.py.\n',
            '// name ' + ' '.join(BONUS_KEYS) + '\n']
    body = ['%s %s\n' % (n, ' '.join(str(x) for x in vals)) for n, vals in gear]
    for p in [os.path.join(ROOT, 'Server', 'configs', 'valoria_gear.txt'), os.path.join(ROOT, 'Client', 'CONTENTS', 'valoria_gear.txt')]:
        open(p, 'w', newline='\r\n').writelines(head + body)

    json.dump(item_map, open(os.path.join(os.path.dirname(__file__), 'item_map.json'), 'w'), indent=1)
    json.dump(frames, open(os.path.join(os.path.dirname(__file__), 'sprite_frames.json'), 'w'), indent=1)

    print('rows', len(out_rows), 'ids %d-%d' % (FIRST_ID, next_id - 1), 'sprite frames', len(frames),
          'gear bonuses', len(gear), 'reused', len(REUSE) + len(reused), [r[1] for r in reused])
    print('skipped', len(skipped), sorted(set(r for _, r in skipped)))


def replace_block(path, block):
    raw = open(path, 'rb').read().decode('latin-1')
    nl = '\r\n' if '\r\n' in raw else '\n'
    text = raw.replace('\r\n', '\n')
    if BEGIN in text:
        a = text.index(BEGIN)
        b = text.index(END, a) + len(END)
        if b < len(text) and text[b] == '\n': b += 1
        text = text[:a] + text[b:]
    if block:
        if not text.endswith('\n'): text += '\n'
        text += ''.join(block)
    open(path, 'wb').write(text.replace('\n', nl).encode('latin-1'))


if __name__ == '__main__':
    main()
