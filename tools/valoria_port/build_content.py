#!/usr/bin/env python3
"""Writes the game's VALORIA content headers from their data files. The dashboard edits the data
files (tools/hb_dashboard); after a change, run this and rebuild the game.

Run from the repo root:  python3 tools/valoria_port/build_content.py

  tools/valoria_port/data/achievements.json -> Source/Shared/ValoriaAchieveData.h
        made from VALORIA's list by build_achievements.py; names, titles and counts can be changed
  tools/valoria_port/data/side_quests.json  -> the kQuests list in Source/Shared/ValoriaSideQuests.h
        (the rest of that header, its rules and types, is kept as it is)
  tools/valoria_port/data/world.json        -> Source/Shared/ValoriaWorld.h
        where the shrines and chests stand (first placed by build_world.py) and what chests hold;
        the gear a chest can hold is VALORIA's craftable gear, from Server/configs/valoria_recipes.txt

Every list keeps its order: saved progress (achievement counters, quest slots) points into them,
so new entries only ever go on the end.
"""
import json, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
DATA = os.path.join(ROOT, 'tools', 'valoria_port', 'data')
SHARED = os.path.join(ROOT, 'Source', 'Shared')
GIVERS = {'McGaffin': ('GIVER_MCGAFFIN', 'hunting'), 'Perry': ('GIVER_PERRY', 'gathering'), 'Devlin': ('GIVER_DEVLIN', 'the arcane')}
OBJ = {'kill': 'OBJ_KILL', 'collect': 'OBJ_COLLECT', 'visit': 'OBJ_VISIT', 'none': 'OBJ_NONE'}
SHRINES = ['might', 'swiftness', 'wisdom', 'fortune', 'vigor']


def c(s):
    return '"' + str(s).replace('\\', '\\\\').replace('"', '\\"') + '"'


def load(name):
    return json.load(open(os.path.join(DATA, name), encoding='utf-8'))


def save(path, text, crlf=True):
    open(path, 'w', encoding='latin-1', newline='\r\n' if crlf else '\n').write(text)


def achievements():
    d = load('achievements.json')
    L = ['// ValoriaAchieveData.h: VALORIA\'s achievements in Helbreath Reimagined.',
         '// Generated by tools/valoria_port/build_content.py from tools/valoria_port/data/achievements.json: do not edit.',
         '// The rules are in ValoriaEnchant.h (Ach); the client draws them in UI\\AchievePanel.cpp, the game',
         '// server counts them in HG Server\\Achievements.cpp.',
         '#pragma once', '', 'namespace Ach {', '',
         'struct Target { const char * npc; const char * name; unsigned char cat; };	// npc = its Npc.cfg name',
         'const int TARGET_COUNT = %d;' % len(d['targets']),
         'static const Target kTargets[TARGET_COUNT] = {']
    L += ['\t{ %s, %s, %d },' % (c(t['npc']), c(t['name']), t['cat']) for t in d['targets']]
    L += ['};', '',
          'struct Def { unsigned char counter, cat, tier; unsigned int count; const char * name; const char * title; };',
          'const int DEF_COUNT = %d;' % len(d['defs']),
          'static const Def kDefs[DEF_COUNT] = {']
    L += ['\t{ %d, %d, %d, %d, %s, %s },' % (a['counter'], a['cat'], a['tier'], a['count'], c(a['name']), c(a['title'])) for a in d['defs']]
    L += ['};', '', '} // namespace Ach', '']
    save(os.path.join(SHARED, 'ValoriaAchieveData.h'), '\n'.join(L))
    return '%d achievements' % len(d['defs'])


def side_quests():
    path = os.path.join(SHARED, 'ValoriaSideQuests.h')
    raw = open(path, encoding='latin-1', newline='').read()
    crlf = '\r\n' in raw
    h = raw.replace('\r\n', '\n')
    head = 'static const Quest kQuests[] = {\n'
    a = h.index(head) + len(head)
    b = h.index('\n};', a)
    L, last = [], None
    for q in load('side_quests.json')['quests']:
        g, kind = GIVERS[q['giver']]
        if q['giver'] != last:
            if last is not None:
                L.append('')
            L.append('\t// ---- %s: %s' % (q['giver'], kind)); last = q['giver']
        for o in q['objectives']:
            if o['type'] != 'none' and (not o['target'] or not o['label'] or o['count'] < 1):
                sys.exit('side quest "%s": an objective needs a target, a label and a count' % q['title'])
        if not any(o['type'] != 'none' for o in q['objectives']):
            sys.exit('side quest "%s" has no objectives' % q['title'])
        objs = ', '.join('{ %s, %s, %d, %d, %s }' % (OBJ[o['type']], c(o['target']), o['count'], o['chance'], c(o['label']))
                         for o in q['objectives'] if o['type'] != 'none')
        L += ['\t{ %s, %d, %s,' % (g, q['min level'], c(q['title'])),
              '\t  %s,' % c(q['offer']), '\t  %s,' % c(q['hand-in']),
              '\t  { %s },' % objs, '\t  %s, %d },' % (c(q['reward item']), q['reward count'])]
    save(path, h[:a] + '\n'.join(L) + h[b:], crlf)
    return '%d side quests' % len(load('side_quests.json')['quests'])


def world():
    d = load('world.json')
    gear = []
    for ln in open(os.path.join(ROOT, 'Server', 'configs', 'valoria_recipes.txt'), encoding='latin-1'):
        ln = ln.strip()
        if not ln or ln.startswith('//'):
            continue
        p = ln.split('\t')
        gear.append((p[0].strip(), min(255, int(p[1]))))
    if not gear:
        sys.exit('valoria_recipes.txt gave no gear: chests would never hold any')
    ch = sorted(d['chests'], key=lambda t: t['tier'])
    assert [t['tier'] for t in ch] == [1, 2, 3, 4, 5], 'chests: one entry for each tier 1-5'
    L = ['// ValoriaWorld.h: VALORIA\'s shrines and treasure chests on Helbreath\'s maps.',
         '// Generated by tools/valoria_port/build_content.py from tools/valoria_port/data/world.json: do not edit.',
         '// (build_world.py placed them first.) The game server runs them in HG Server\\WorldProps.cpp; the',
         '// client draws them in UI\\WorldProps.cpp.',
         '#pragma once', '', 'namespace World {', '',
         'enum Kind { SHRINE_MIGHT, SHRINE_SWIFTNESS, SHRINE_WISDOM, SHRINE_FORTUNE, SHRINE_VIGOR, CHEST };',
         'const int SHRINE_KINDS = 5;',
         'const int SHRINE_RECHARGE = 300;	// seconds, as VALORIA (the blessing itself lasts 240: Shared\\ValoriaUse.h)',
         'const int CHEST_REFILL   = 900;',
         'const int TOUCH_RANGE    = 2;		// tiles',
         '',
         'struct Prop { const char * map; short x, y; unsigned char kind, tier; };',
         'static const Prop kProps[] = {']
    for p in d['props']:
        if p['kind'] == 'chest':
            L.append('\t{ %s, %d, %d, CHEST, %d },' % (c(p['map']), p['x'], p['y'], p['tier']))
        else:
            L.append('\t{ %s, %d, %d, %d, 0 },' % (c(p['map']), p['x'], p['y'], SHRINES.index(p['kind'].replace('shrine of ', ''))))
    L += ['};', 'const int PROP_COUNT = (int)(sizeof(kProps) / sizeof(kProps[0]));', '',
          '// What a chest holds, by its tier (1-5): gold (this amount x1 to x3), one to three potions, one',
          '// crafting material, and at "gear chance" percent one piece of VALORIA gear of its tier (kGear:',
          '// the craftable items and the level they need; the server keeps the ones that are worn or wielded).',
          'static const unsigned short kChestGold[5] = { %s };' % ', '.join(str(t['gold']) for t in ch),
          'static const char * const kChestPotion[5] = { %s };' % ', '.join(c(t['potion']) for t in ch),
          'static const char * const kChestMaterial[5] = { %s };' % ', '.join(c(t['material']) for t in ch),
          'static const unsigned char kChestGearPct[5] = { %s };' % ', '.join(str(t['gear chance']) for t in ch),
          'inline int ChestGearPct(int tier) { return (tier >= 1 && tier <= 5) ? kChestGearPct[tier - 1] : 0; }',
          'struct Gear { const char * name; unsigned char level; };',
          'static const Gear kGear[] = {']
    L += ['\t{ %s, %d },' % (c(n), lv) for n, lv in gear]
    L += ['};', 'const int GEAR_COUNT = (int)(sizeof(kGear) / sizeof(kGear[0]));', '',
          'inline bool SameMap(const char * a, const char * b)',
          '{', '\tfor (; *a && *b; a++, b++) if ((*a | 0x20) != (*b | 0x20)) return false;', '\treturn *a == 0 && *b == 0;', '}',
          '', '} // namespace World', '']
    save(os.path.join(SHARED, 'ValoriaWorld.h'), '\n'.join(L))
    return '%d shrines and chests, %d gear' % (len(d['props']), len(gear))


if __name__ == '__main__':
    print('; '.join([achievements(), side_quests(), world()]))
